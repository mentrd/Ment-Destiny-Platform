/**
 * 易經六十四卦資料（通行本／周易卦序）
 * binary 約定：6 位字串，初爻（最下爻）在最左，1=陽爻、0=陰爻；下卦占前三位、上卦占後三位。
 * 卦辭（judgment）與爻辭原文為公有領域古籍文本；modern／lines 白話與 advice 為本站原創解讀，
 * 定位為娛樂、文化與自我探索參考。
 */

export interface Hexagram {
  /** 通行本卦序 1–64 */
  no: number;
  /** 卦名（單名，如「乾」） */
  name: string;
  /** 全名（含上下卦，如「乾為天」） */
  fullName: string;
  /** 卦象符號（U+4DC0 起，依卦序連續） */
  symbol: string;
  /** 6 位字串，初爻在最左，1=陽 0=陰 */
  binary: string;
  /** 卦辭原文 */
  judgment: string;
  /** 白話總解（約 80–140 字） */
  modern: string;
  /** 六爻，初爻在 index 0，格式「爻題：爻辭——白話短解」 */
  lines: string[];
  /** 行動建議（約 40–70 字） */
  advice: string;
  /** 關鍵詞 3–5 個 */
  keywords: string[];
}

/** 依 binary 與爻位產生爻題（初/上在前、二三四五在後；陽九陰六） */
function lineTitle(binary: string, i: number): string {
  const num = binary[i] === "1" ? "九" : "六";
  if (i === 0) return `初${num}`;
  if (i === 5) return `上${num}`;
  return `${num}${["", "二", "三", "四", "五"][i]}`;
}

/** 卦象符號：Unicode 易經六十四卦區塊 U+4DC0（乾）起，依通行本卦序連續 */
function hexSymbol(no: number): string {
  return String.fromCodePoint(0x4dbf + no);
}

interface RawHex {
  no: number;
  name: string;
  fullName: string;
  binary: string;
  judgment: string;
  modern: string;
  /** 六爻爻辭「爻辭——白話短解」，初爻在 index 0；爻題於建構時自動加上 */
  lines: string[];
  advice: string;
  keywords: string[];
}

function build(raw: RawHex): Hexagram {
  return {
    no: raw.no,
    name: raw.name,
    fullName: raw.fullName,
    symbol: hexSymbol(raw.no),
    binary: raw.binary,
    judgment: raw.judgment,
    modern: raw.modern,
    lines: raw.lines.map((t, i) => `${lineTitle(raw.binary, i)}：${t}`),
    advice: raw.advice,
    keywords: raw.keywords,
  };
}

