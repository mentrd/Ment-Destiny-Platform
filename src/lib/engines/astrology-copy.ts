/**
 * 由太陽/月亮/上升與行星元素分布，組合出綜合性格分析（回傳段落陣列）
 */
export function buildOverview(
  sun: ZodiacSign,
  moon: ZodiacSign,
  asc: ZodiacSign | null,
  planets: Pick<PlanetPosition, "sign">[]
): string[] {
  const p1 =
    `你的太陽落在${sun.name}，${ELEMENT_CORE[sun.element]}，這是你最想活出的樣子；` +
    `月亮在${moon.name}，代表私底下的你${ELEMENT_INNER[moon.element]}。` +
    (asc
      ? `而上升${asc.name}讓你在初次見面時${ELEMENT_OUTER[asc.element]}。` +
        (asc.element !== sun.element ? "外在形象與內在核心不完全相同，這正是別人「越認識你越覺得有層次」的原因。" : "由內而外的能量一致，你給人的印象與真實的你相當接近。")
      : "");

  const counts: Record<Element, number> = { fire: 0, earth: 0, air: 0, water: 0 };
  for (const p of planets) counts[p.sign.element] += 1;
  const entries = Object.entries(counts) as [Element, number][];
  entries.sort((a, b) => b[1] - a[1]);
  const [topEl, topN] = entries[0];
  const balanced = entries[1][1] === topN;

  const detail = entries
    .filter(([, n]) => n > 0)
    .map(([el, n]) => `${ELEMENT_LABELS[el]} ${n} 顆`)
    .join("、");

  const p2 = balanced
    ? `你的七顆行星元素分布相當平均（${detail}），代表你能在行動、務實、思考與感受之間切換，是適應力很好的均衡型人格。`
    : `${ELEMENT_DOMINANT[topEl]}（七顆行星中${detail}。）`;

  const p3 =
    (sun.element === moon.element
      ? `太陽與月亮同屬${ELEMENT_LABELS[sun.element]}，你想要的與你需要的方向一致，內外相對和諧，能量集中。`
      : `太陽與月亮分屬${ELEMENT_LABELS[sun.element]}與${ELEMENT_LABELS[moon.element]}，理想中的自己與內在需求偶爾拉扯，但這也讓你比別人多了一種視角與彈性。`) +
    "星盤沒有好壞，每個配置都是獨特的組合；把它當作認識自己的地圖，你會更懂得欣賞自己本來的樣子。";

  return [p1, p2, p3];
}
