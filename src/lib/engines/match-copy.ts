/** 依分數帶與型別取一組文案（以傳入 rng 選取，確保可重現） */
export function getMatchCopy(
  rng: () => number,
  type: MatchType,
  score: number
): MatchCopyGroup {
  const pool = MATCH_COPY[type][bandOf(score)];
  return pool[Math.floor(rng() * pool.length)];
}
